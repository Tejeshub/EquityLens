from typing import Optional
from uuid import UUID

from pydantic import BaseModel

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import select
from sqlalchemy.orm import Session

from core import policy, ratelimit
from core.db import get_session
from core.orm import Company, ResearchJob, ResearchReport, User
from core.security import current_user
from core.settings import get_settings
from services.research import jobs, service
from services.research.models import ResearchOut

router = APIRouter(prefix="/api/v1/research", tags=["research"])


def _company(db: Session, company_id: UUID) -> Company:
    co = db.get(Company, company_id)
    if co is None or not co.active or not co.listings:
        raise HTTPException(status_code=404, detail="Company not found")
    return co


@router.get("/latest", response_model=ResearchOut)
def latest(company_id: UUID = Query(...), db: Session = Depends(get_session), user: User = Depends(current_user)):
    """Most recent report generated by the *current user* for this company (never another user's)."""
    _company(db, company_id)
    r = db.scalar(select(ResearchReport).where(ResearchReport.user_id == user.id, ResearchReport.company_id == company_id)
                  .order_by(ResearchReport.created_at.desc()))
    if r is None:
        raise HTTPException(status_code=404, detail={"code": "no_research", "message": "No research has been generated for this company yet"})
    return ResearchOut.model_validate(r.result)


class JobOut(BaseModel):
    job_id: str
    company_id: str
    status: str  # queued | running | complete | failed
    error: Optional[dict] = None
    report_id: Optional[str] = None
    report: Optional[ResearchOut] = None
    created_at: str
    started_at: Optional[str] = None
    finished_at: Optional[str] = None
    poll_after_ms: int = 2000


def _job_out(db: Session, job: ResearchJob) -> JobOut:
    report = None
    if job.status == "complete" and job.report_id:
        r = db.get(ResearchReport, job.report_id)
        report = ResearchOut.model_validate(r.result) if r else None
        if report is not None:  # a report that predates the job was reused (identical evidence), not regenerated
            report.reused = r.created_at < job.created_at
    iso = lambda d: d.isoformat() if d else None
    return JobOut(job_id=str(job.id), company_id=str(job.company_id), status=job.status,
                  error={"code": job.error_code, "message": job.error_message} if job.status == "failed" else None,
                  report_id=str(job.report_id) if job.report_id else None, report=report,
                  created_at=iso(job.created_at), started_at=iso(job.started_at), finished_at=iso(job.finished_at))


@router.post("/{company_id}", response_model=JobOut, status_code=202)
def generate(company_id: UUID, db: Session = Depends(get_session), user: User = Depends(current_user)):
    """Explicit user action. Creates (or returns the already-active) background job and returns immediately; poll
    GET /research/jobs/{job_id}. The per-user daily budget is charged by the worker only when new model work runs."""
    policy.require_any("screener", "news")  # no evidence source enabled -> refuse (no job, no model call)
    co = _company(db, company_id)
    ratelimit.enforce(db, f"research_attempts:user:{user.id}", 20, 3600, "Too many research requests; slow down")
    job, created = jobs.submit(db, user, co)
    if created:
        jobs.start(job.id)
        db.refresh(job)
    return _job_out(db, job)


@router.get("/active", response_model=JobOut)
def active_job(company_id: UUID = Query(...), db: Session = Depends(get_session), user: User = Depends(current_user)):
    """The caller's queued/running job for this company, so the UI can resume polling after a reload. 404 when none."""
    _company(db, company_id)
    job = db.scalar(select(ResearchJob).where(ResearchJob.user_id == user.id, ResearchJob.company_id == company_id,
                                              ResearchJob.status.in_(("queued", "running"))))
    if job is not None:
        jobs.expire_if_stale(db, job)
    if job is None or job.status not in ("queued", "running"):
        raise HTTPException(status_code=404, detail={"code": "no_active_job", "message": "No research job is running for this company"})
    return _job_out(db, job)


@router.get("/jobs/{job_id}", response_model=JobOut)
def job_status(job_id: UUID, db: Session = Depends(get_session), user: User = Depends(current_user)):
    job = db.scalar(select(ResearchJob).where(ResearchJob.id == job_id, ResearchJob.user_id == user.id))
    if job is None:
        raise HTTPException(status_code=404, detail="Job not found")
    return _job_out(db, jobs.expire_if_stale(db, job))


# Declared last: a bare '/{report_id}' would otherwise shadow the fixed paths '/latest' and '/active'.
@router.get("/{report_id}", response_model=ResearchOut)
def get_report(report_id: UUID, db: Session = Depends(get_session), user: User = Depends(current_user)):
    r = db.scalar(select(ResearchReport).where(ResearchReport.id == report_id, ResearchReport.user_id == user.id))
    if r is None:
        raise HTTPException(status_code=404, detail="Report not found")
    return ResearchOut.model_validate(r.result)
